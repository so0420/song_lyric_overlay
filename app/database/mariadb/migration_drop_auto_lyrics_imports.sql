-- ============================================
-- 자동 가사(LRCLIB) '적용 기록' 기능 제거
-- ============================================
-- 적용 안내:
--   python migrate.py --file drop_auto_lyrics_imports
--
-- 배경:
--   이용자가 자동 가사를 적용하면 관리자 검토·정식 등록용으로 그 내역을
--   auto_lyrics_imports 에 남겨 왔다. 이 기능(기록 저장 API, 관리자 검토 화면,
--   편집기 연동)을 통째로 제거하면서 테이블도 함께 정리한다.
--
--   노래하기 화면의 자동 가사 검색·적용 자체는 그대로 남는다. 브라우저가
--   lrclib.net 을 직접 호출해 화면·OBS 에 표시할 뿐 서버에 기록하지 않는다.
--
-- 주의:
--   이 테이블에는 이용자가 적용한 LRCLIB 원본 가사 텍스트와 적용자 ID가 들어 있다.
--   되돌릴 수 없으므로 필요하면 적용 전에 백업해 두어야 한다.
--     mysqldump ... song_lyric auto_lyrics_imports > auto_lyrics_imports_backup.sql
-- ============================================

DROP TABLE IF EXISTS `auto_lyrics_imports`;
