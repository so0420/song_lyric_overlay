// 지정한 family 의 @font-face(또는 CSS import)를 <head> 에 1회 주입한다.
window.ensureOverlayFont = function (family) {
  if (!family) return;
  var f = (window.OVERLAY_FONTS || []).find(function (x) { return x.family === family; });
  if (!f) return; // 목록에 없는 폰트(내장/시스템 폰트)는 별도 로딩 불필요
  var id = 'overlayfont-' + family.replace(/[^a-zA-Z0-9_-]/g, '');
  if (document.getElementById(id)) return;
  if (f.format === 'css-import' || f.format === 'css') {
    var link = document.createElement('link');
    link.id = id; link.rel = 'stylesheet'; link.href = f.url;
    document.head.appendChild(link);
  } else {
    var style = document.createElement('style');
    style.id = id;
    style.textContent = "@font-face{font-family:'" + f.family + "';src:url('" + f.url + "') format('" + f.format + "');font-display:swap;}";
    document.head.appendChild(style);
  }
};

// 목록의 모든 폰트를 주입한다(설정 페이지 드롭다운 미리보기용).
window.injectAllOverlayFonts = function () {
  (window.OVERLAY_FONTS || []).forEach(function (f) { window.ensureOverlayFont(f.family); });
};

// 글꼴 드롭다운에 목록의 폰트를 옵션으로 추가한다(이미 있는 data-value 는 건너뜀).
window.buildOverlayFontOptions = function (dropdownEl) {
  if (!dropdownEl) return;
  var existing = {};
  dropdownEl.querySelectorAll('.font-select-option').forEach(function (o) { existing[o.dataset.value] = true; });
  (window.OVERLAY_FONTS || []).forEach(function (f) {
    if (existing[f.family]) return;
    var div = document.createElement('div');
    div.className = 'font-select-option';
    div.dataset.value = f.family;
    div.style.fontFamily = "'" + f.family + "', sans-serif";
    div.textContent = f.label;
    dropdownEl.appendChild(div);
  });
};
